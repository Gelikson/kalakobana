// Drop accidental non-word tokens (e.g. stray punctuation) so the lists stay clean.
const DICT = Object.fromEntries(
  Object.entries(RAW).map(([cat, text]) => [
    cat,
    new Set(text.split(/\s+/).map((w) => w.trim()).filter((w) => ONLY_GEORGIAN.test(w))),
  ]),
);

export function inDictionary(category, word) {
  const set = DICT[category];
  return !!set && set.has(normalizeGeorgian(word));
}

export function dictionarySize() {
  return Object.fromEntries(Object.entries(DICT).map(([k, v]) => [k, v.size]));
}

export function validateLocal(category, word, letter) {
  const w = normalizeGeorgian(word);
  const fmt = checkFormat(w, letter);
  if (!fmt.ok) return { status: 'invalid', reason: fmt.reason };
  if (inDictionary(category, w)) return { status: 'valid' };
  return { status: 'unknown' };
}
