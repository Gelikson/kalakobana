// georgianDictionary.js
// Georgian word validation service for Kalakobana (ქალაქობანა).
//
//   normalizeGeorgian(str)              -> trimmed, NFC-normalized, single-spaced string
//   checkFormat(word, letter)           -> { ok, reason? }   (rules a, b, c)
//   inDictionary(category, word)        -> boolean
//   validateLocal(category, word, letter)
//        -> { status: 'valid' | 'invalid' | 'unknown', reason? }
//           'unknown' = well-formed but not in the built-in list -> use the API/AI fallback.
//
// The lists below are a SEED. Extend them freely: one space-separated string per category.

/** Mkhedruli range required by the spec. */
export const GEORGIAN_CHAR = /[\u10D0-\u10FA]/;
const ONLY_GEORGIAN = /^[\u10D0-\u10FA]+(?: [\u10D0-\u10FA]+)*$/; // letters, single inner spaces

export function normalizeGeorgian(input) {
  return String(input ?? '')
    .normalize('NFC')
    .replace(/[\u200B-\u200D\uFEFF]/g, '') // zero-width chars
    .replace(/\s+/g, ' ')
    .trim();
}

export function checkFormat(word, letter) {
  const w = normalizeGeorgian(word);
  if (!w) return { ok: false, reason: 'ცარიელია' };
  if (!ONLY_GEORGIAN.test(w)) return { ok: false, reason: 'მხოლოდ ქართული ასოები' };
  if (w[0] !== letter) return { ok: false, reason: `უნდა იწყებოდეს ასოთი „${letter}“` };
  if (w.replace(/ /g, '').length < 2) return { ok: false, reason: 'ძალიან მოკლეა' };
  return { ok: true };
}

